#!/usr/bin/env node
"use strict";

// Edge persistence acceptance: the Caddy config that serves :80/:443 is the
// exact file persisted at /etc/caddy/Caddyfile, and the whole stack still
// answers after `systemctl reload caddy`.
//
// Contract: gc-mwhae0qj — prints EDGE_PERSISTENCE_OK only when every check
// passes. Real files, real TLS and real systemd: no mocks.

const crypto = require("node:crypto");
const fs = require("node:fs");
const http = require("node:http");
const https = require("node:https");
const path = require("node:path");
const { execFileSync, spawnSync } = require("node:child_process");

const ROOT = path.resolve(__dirname, "..");
const PERSISTED = "/etc/caddy/Caddyfile";
const RENDERED = path.join(ROOT, "dist", "deploy", "Caddyfile");
const REPORT = path.join(ROOT, "logs", "verify", "edge-persistence", "REPORT.md");
const EXPECTED_HOSTS = [
  "adapter.localhost",
  "ads.localhost",
  "combined.localhost",
  "localhost",
  "ocr.localhost",
  "public.localhost",
  "screen.localhost",
  "tts.localhost",
].sort();
const AGENT_IDS = [
  "mission",
  "code-guru",
  "bug-hunter",
  "security-hero",
  "perf-wizard",
  "doc-king",
  "qa-tyrant",
  "team-heart",
  "customer-experience-specialist",
  "ecommerce-operations-analyst",
];

function die(message) {
  console.error(`FAIL ${message}`);
  process.exit(1);
}

function sha256(file) {
  return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

function request(options) {
  const { protocol = "http", host = "localhost", port, servername, path: target = "/", method = "GET", headers = {}, body, timeoutMs = 15000 } = options;
  return new Promise((resolve) => {
    const mod = protocol === "https" ? https : http;
    const req = mod.request(
      {
        host,
        port,
        path: target,
        method,
        servername,
        rejectUnauthorized: false,
        headers: { host: servername || host, ...headers },
        timeout: timeoutMs,
      },
      (res) => {
        const chunks = [];
        res.on("data", (chunk) => chunks.push(chunk));
        res.on("end", () =>
          resolve({ status: res.statusCode, headers: res.headers, body: Buffer.concat(chunks).toString("utf8") }),
        );
      },
    );
    req.on("timeout", () => req.destroy(new Error("timeout")));
    req.on("error", (error) => resolve({ status: 0, headers: {}, body: "", error: String(error.message || error) }));
    if (body) req.write(body);
    req.end();
  });
}

function json(text) {
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

function isActive(unit, user = false) {
  const args = user ? ["--user", "is-active", unit] : ["is-active", unit];
  try {
    return execFileSync("systemctl", args, { encoding: "utf8" }).trim();
  } catch (error) {
    return String(error.stdout || "").trim();
  }
}

function run(label, script, marker) {
  const started = Date.now();
  const result = spawnSync(process.execPath, [path.join(ROOT, "tests", script)], {
    cwd: ROOT,
    encoding: "utf8",
    timeout: 110000,
  });
  const output = `${result.stdout || ""}${result.stderr || ""}`;
  const elapsed = Date.now() - started;
  if (result.status !== 0) die(`${label} exited ${result.status} in ${elapsed}ms: ${output.slice(-600)}`);
  if (!output.includes(marker)) die(`${label} did not print ${marker}: ${output.slice(-400)}`);
  console.log(output.trim());
  console.log(`OK   ${label} exit 0 in ${elapsed}ms (${marker})`);
  return output;
}

function writeReport(data) {
  const bridgeList = data.bridgeIds.join(", ");
  const lines = [
    "# Edge persistence verification",
    "",
    "Generated by `tests/edge-persistence-check.js` from the real run.",
    "",
    "Generated at: " + new Date().toISOString(),
    "- Source check: `tests/edge-persistence-check.js` -> `EDGE_PERSISTENCE_OK`",
    "",
    "- Persisted Caddyfile: `" + PERSISTED + "`",
    "- SHA-256: `" + data.persistedHash + "`",
    "- Matches `dist/deploy/Caddyfile`: yes",
    "- Hosts: " + data.hosts.join(", "),
    "- caddy validate: exit 0",
    "- Gateway MainPID: " + data.mainPid,
    "- Health: agents=" + data.agents + ", models=" + data.models,
    "- ocr.localhost: HTTP " + data.toolStatus,
    "- Bridge models: " + bridgeList,
    "- Ollama loaded: lfm3:1.7b",
    "",
    "Full gate:",
    "",
    "```",
    data.fullStackOutput.trim(),
    "```",
    "",
    "EDGE_PERSISTENCE_OK",
    "",
  ];
  fs.mkdirSync(path.dirname(REPORT), { recursive: true });
  fs.writeFileSync(REPORT, lines.join("\n"), "utf8");
  console.log("OK   report written: " + REPORT);
}

async function main() {
  // 1. The persisted file is byte-identical to the rendered file.
  if (!fs.existsSync(PERSISTED)) die(`${PERSISTED} is missing`);
  const persistedHash = sha256(PERSISTED);
  const renderedHash = sha256(RENDERED);
  if (persistedHash !== renderedHash) {
    die(`persisted Caddyfile differs: ${persistedHash} != ${renderedHash}`);
  }
  console.log(`OK   persisted Caddyfile sha256=${persistedHash} (matches dist)`);

  // 2. Exactly eight bare-host site addresses.
  const text = fs.readFileSync(PERSISTED, "utf8");
  const siteLines = text.split("\n").filter((line) => line.startsWith("https://"));
  for (const line of siteLines) {
    if ((line.match(/https:\/\//g) || []).length !== 1) die(`scheme inside host: ${line}`);
  }
  const hosts = siteLines.map((line) => line.replace(/^https:\/\//, "").replace(/\s*\{$/, "").trim()).sort();
  if (JSON.stringify(hosts) !== JSON.stringify(EXPECTED_HOSTS)) {
    die(`persisted hosts mismatch: ${JSON.stringify(hosts)}`);
  }
  console.log(`OK   persisted hosts: ${hosts.join(", ")}`);

  // 3. Caddy accepts the persisted file.
  const validate = spawnSync("caddy", ["validate", "--config", PERSISTED, "--adapter", "caddyfile"], {
    encoding: "utf8",
    timeout: 30000,
  });
  if (validate.status !== 0) {
    die(`caddy validate failed: ${(validate.stderr || validate.stdout || "").slice(0, 300)}`);
  }
  console.log("OK   caddy validate persisted exit 0");

  // 4. Caddy and the gateway unit are active; the unit owns the dist runtime.
  const caddyActive = isActive("caddy");
  if (caddyActive !== "active") die(`caddy.service is ${caddyActive || "unknown"}`);
  const gatewayActive = isActive("zombiecoder-gateway.service", true);
  if (gatewayActive !== "active") die(`zombiecoder-gateway.service is ${gatewayActive || "unknown"}`);
  const shown = execFileSync("systemctl", ["--user", "show", "zombiecoder-gateway.service", "-p", "MainPID"], {
    encoding: "utf8",
  });
  const mainPid = Number((shown.match(/MainPID=(\d+)/) || [])[1] || 0);
  if (!mainPid) die("gateway unit has no MainPID");
  const cmdline = fs.readFileSync(`/proc/${mainPid}/cmdline`, "utf8").replace(/\0/g, " ").trim();
  if (!cmdline.includes("dist/start.js")) die(`MainPID ${mainPid} is not the dist runtime: ${cmdline}`);
  console.log(`OK   caddy active; gateway active MainPID=${mainPid} (${cmdline})`);

  // 5. :80 redirects to :443, health is 200, a tool subdomain routes.
  const redirect = await request({ port: 80, servername: "localhost", path: "/" });
  if (redirect.status !== 308) die(`http://localhost/ expected 308, got ${redirect.status || redirect.error}`);
  const location = String(redirect.headers.location || "");
  if (!/^https:\/\/localhost\/?$/.test(location)) die(`redirect Location wrong: ${location}`);
  console.log(`OK   :80 -> ${location} (308)`);

  const health = await request({ protocol: "https", port: 443, servername: "localhost", path: "/health" });
  const healthBody = json(health.body);
  if (health.status !== 200 || !healthBody || healthBody.healthy !== true) {
    die(`https://localhost/health expected 200 healthy:true, got ${health.status} ${health.body.slice(0, 160)}`);
  }
  console.log(`OK   https://localhost/health 200 (agents=${healthBody.agents}, models=${healthBody.models})`);

  const tool = await request({ protocol: "https", port: 443, servername: "ocr.localhost", path: "/" });
  if (tool.status === 0) die(`ocr.localhost TLS failed: ${tool.error}`);
  if (tool.status === 502) die("ocr.localhost returned 502: upstream not reachable");
  console.log(`OK   https://ocr.localhost/ -> HTTP ${tool.status} (routed)`);

  // 6. The bridge must not discover the gateway's own agent ids.
  const bridge = await request({ port: 11435, path: "/v1/models" });
  const bridgeBody = json(bridge.body);
  if (bridge.status !== 200 || !bridgeBody || !Array.isArray(bridgeBody.data)) {
    die(`bridge /v1/models unavailable (HTTP ${bridge.status})`);
  }
  const ids = bridgeBody.data.map((model) => String(model.id));
  const leaked = ids.filter((id) => AGENT_IDS.includes(id));
  if (leaked.length > 0) die(`bridge discovered local gateway agent ids: ${leaked.join(", ")}`);
  console.log(`OK   bridge models: ${ids.join(", ")} (no local gateway agent ids)`);

  // 7. The full acceptance gate still passes after the reload.
  const fullStackOutput = run("full-stack", "full-stack-check.js", "FULL_STACK_OK");

  writeReport({
    persistedHash,
    hosts,
    mainPid,
    agents: healthBody.agents,
    models: healthBody.models,
    toolStatus: tool.status,
    bridgeIds: ids,
    fullStackOutput,
  });

  console.log("EDGE_PERSISTENCE_OK");
}

main().catch((error) => die(String(error?.stack || error)));
