"use strict";

/**
 * modules/workspace-adapter.js — the seam between the two independent modules.
 *
 * The OpenCode plugin owns `<project>/.zombiecoder/` (its spec §3: SSOT.md,
 * syllabus.md, memory/, .state/). The gateway must keep working in
 * environments where that plugin is not installed, so it owns a different
 * directory: `<project>/.zombie/` (override with ZC_SERVER_STATE_DIR).
 *
 * Rules enforced here:
 *   - the server only creates `.zombie/`; it never creates `.zombiecoder/`;
 *   - plugin files are read-only inputs, never rewritten;
 *   - the server syllabus is seeded from the plugin syllabus on first use and
 *     later reads merge plugin-only entries without duplicating server ones;
 *   - a compact 12-hex workspace id maps to a directory through a small
 *     registry, so UDS/gRPC headers never need the full path.
 *
 * This module must not import the plugin or any editor package.
 */

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PLUGIN_DIR = ".zombiecoder";
const DEFAULT_SERVER_DIR = ".zombie";
const MAX_REGISTRY_ENTRIES = 200;
const MAX_MERGE_BYTES = 16 * 1024 * 1024;

function serverDirName() {
  const raw = String(process.env.ZC_SERVER_STATE_DIR || "").trim();
  if (!raw) return DEFAULT_SERVER_DIR;
  // A single relative directory name only: no traversal, no absolute path.
  if (!/^\.?[A-Za-z0-9._-]+$/.test(raw) || raw === "." || raw === ".." || raw.includes("/")) {
    return DEFAULT_SERVER_DIR;
  }
  return raw.startsWith(".") ? raw : "." + raw;
}

const SERVER_DIR = serverDirName();

function serverPaths(root) {
  const base = path.resolve(root || process.cwd());
  const dir = path.join(base, SERVER_DIR);
  return {
    root: base,
    dir,
    ssot: path.join(dir, "SSOT.md"),
    syllabus: path.join(dir, "syllabus.md"),
    memory: path.join(dir, "memory"),
    sessions: path.join(dir, "memory", "sessions"),
    state: path.join(dir, ".state"),
  };
}

function pluginPaths(root) {
  const base = path.resolve(root || process.cwd());
  const dir = path.join(base, PLUGIN_DIR);
  return {
    root: base,
    dir,
    ssot: path.join(dir, "SSOT.md"),
    syllabus: path.join(dir, "syllabus.md"),
    memory: path.join(dir, "memory"),
    state: path.join(dir, ".state"),
  };
}

function readBounded(file) {
  try {
    const stat = fs.statSync(file);
    if (!stat.isFile()) return { text: "", mtimeMs: 0, size: 0, truncated: false };
    const length = Math.min(stat.size, MAX_MERGE_BYTES);
    const fd = fs.openSync(file, "r");
    const buffer = Buffer.alloc(length);
    try {
      fs.readSync(fd, buffer, 0, length, 0);
    } finally {
      fs.closeSync(fd);
    }
    return {
      text: buffer.toString("utf8"),
      mtimeMs: stat.mtimeMs,
      size: stat.size,
      truncated: stat.size > length,
    };
  } catch (_) {
    return { text: "", mtimeMs: 0, size: 0, truncated: false };
  }
}

function ensureDir(dir, created) {
  if (fs.existsSync(dir)) return;
  fs.mkdirSync(dir, { recursive: true });
  if (created) created.push(dir);
}

function writeIfMissing(file, body, created) {
  if (fs.existsSync(file)) return false;
  fs.writeFileSync(file, body, "utf8");
  if (created) created.push(file);
  return true;
}

const SEED_SSOT = [
  "# Project SSOT",
  "",
  "> Generated by modules/workspace-adapter.js on first connect.",
  "> Replace the sections below with the real project facts.",
  "",
  "## Project",
  "",
  "- Name: (not detected yet)",
  "- Root: (set by workspace resolver)",
  "",
  "## Stack",
  "",
  "- (not detected yet)",
  "",
].join("\n");

const SEED_SYLLABUS = [
  "# Agent Syllabus",
  "",
  "> Server-owned append-only project memory (.zombie/syllabus.md).",
  "> Plugin entries from .zombiecoder/syllabus.md are merged read-only.",
  "",
].join("\n");

/**
 * Create the server-owned workspace layout. The plugin directory is never
 * created and never modified. Existing server files are never overwritten.
 *
 * @returns {{root: string, paths: object, created: string[],
 *            seeded: {ssot: boolean, syllabus: boolean},
 *            fromPlugin: {ssot: boolean, syllabus: boolean}}}
 */
function ensureServerWorkspace(root, opts) {
  const o = opts || {};
  const paths = serverPaths(root);
  const created = [];
  ensureDir(paths.dir, created);
  ensureDir(paths.memory, created);
  ensureDir(paths.sessions, created);
  ensureDir(paths.state, created);

  const plugin = pluginPaths(paths.root);
  const fromPlugin = { ssot: false, syllabus: false };
  const seeded = { ssot: false, syllabus: false };

  if (!fs.existsSync(paths.ssot)) {
    const pluginSsot = readBounded(plugin.ssot).text;
    if (pluginSsot.trim()) {
      writeIfMissing(paths.ssot, pluginSsot, created);
      fromPlugin.ssot = true;
    } else {
      seeded.ssot = writeIfMissing(paths.ssot, SEED_SSOT, created);
    }
  }

  if (!fs.existsSync(paths.syllabus)) {
    const pluginSyllabus = readBounded(plugin.syllabus).text;
    if (pluginSyllabus.trim()) {
      writeIfMissing(paths.syllabus, pluginSyllabus, created);
      fromPlugin.syllabus = true;
    } else {
      seeded.syllabus = writeIfMissing(paths.syllabus, SEED_SYLLABUS, created);
    }
  }

  return { root: paths.root, paths, created, seeded, fromPlugin };
}

/**
 * Split an append-only syllabus into a header and `###` entry blocks.
 * Entries keep their heading and marker comment.
 */
function splitEntries(text) {
  const value = String(text || "");
  const match = /^### /m.exec(value);
  if (!match) return { header: value, entries: [] };
  const header = value.slice(0, match.index);
  const body = value.slice(match.index);
  const parts = body.split(/^(?=### )/m).filter((part) => part.trim());
  return { header, entries: parts };
}

function entryIdentity(block) {
  const marker = /<!--\s*zc-entry:([A-Za-z0-9]+)/.exec(block);
  if (marker) return "key:" + marker[1];
  return "sha:" + crypto.createHash("sha256").update(block.trim()).digest("hex");
}

const _mergeCache = new Map(); // root -> {server, plugin, text, added, entries}

/**
 * Read the server syllabus and merge plugin-only entries read-only.
 * The server file stays the write target; the plugin file is never touched.
 */
function readMergedSyllabus(root) {
  const paths = serverPaths(root);
  const plugin = pluginPaths(paths.root);
  const serverRead = readBounded(paths.syllabus);
  const pluginRead = readBounded(plugin.syllabus);

  const cacheKey = paths.root;
  const cached = _mergeCache.get(cacheKey);
  if (
    cached &&
    cached.serverMtime === serverRead.mtimeMs &&
    cached.serverSize === serverRead.size &&
    cached.pluginMtime === pluginRead.mtimeMs &&
    cached.pluginSize === pluginRead.size
  ) {
    return cached;
  }

  if (!pluginRead.text.trim()) {
    const result = {
      text: serverRead.text.trim(),
      server: Boolean(serverRead.text.trim()),
      plugin: false,
      added: 0,
      entries: splitEntries(serverRead.text).entries.length,
      serverMtime: serverRead.mtimeMs,
      serverSize: serverRead.size,
      pluginMtime: pluginRead.mtimeMs,
      pluginSize: pluginRead.size,
      truncated: serverRead.truncated || pluginRead.truncated,
    };
    _mergeCache.set(cacheKey, result);
    return result;
  }

  if (!serverRead.text.trim()) {
    const result = {
      text: pluginRead.text.trim(),
      server: false,
      plugin: true,
      added: 0,
      entries: splitEntries(pluginRead.text).entries.length,
      serverMtime: serverRead.mtimeMs,
      serverSize: serverRead.size,
      pluginMtime: pluginRead.mtimeMs,
      pluginSize: pluginRead.size,
      truncated: pluginRead.truncated,
    };
    _mergeCache.set(cacheKey, result);
    return result;
  }

  const serverParts = splitEntries(serverRead.text);
  const pluginParts = splitEntries(pluginRead.text);
  const seen = new Set(serverParts.entries.map(entryIdentity));
  const additions = [];
  for (const block of pluginParts.entries) {
    const identity = entryIdentity(block);
    if (seen.has(identity)) continue;
    seen.add(identity);
    additions.push(block.trim());
  }

  const base = serverRead.text.replace(/\s*$/, "");
  const text = additions.length ? base + "\n\n" + additions.join("\n\n") + "\n" : base + "\n";
  const result = {
    text: text.trim(),
    server: true,
    plugin: true,
    added: additions.length,
    entries: serverParts.entries.length + additions.length,
    serverMtime: serverRead.mtimeMs,
    serverSize: serverRead.size,
    pluginMtime: pluginRead.mtimeMs,
    pluginSize: pluginRead.size,
    truncated: serverRead.truncated || pluginRead.truncated,
  };
  _mergeCache.set(cacheKey, result);
  return result;
}

function clearMergeCache() {
  _mergeCache.clear();
}

/** Stable 12-hex id for a workspace path. */
function workspaceId(root) {
  const resolved = path.resolve(root || process.cwd());
  let real = resolved;
  try {
    real = fs.realpathSync(resolved);
  } catch (_) {
    /* a not-yet-created workspace keeps its resolved path */
  }
  return crypto.createHash("sha256").update(real).digest("hex").slice(0, 12);
}

function registryPath(opts) {
  const o = opts || {};
  return path.resolve(
    o.registry || process.env.ZC_WORKSPACE_REGISTRY || path.join(ROOT, "data", "workspaces.json"),
  );
}

function readRegistry(opts) {
  const file = registryPath(opts);
  try {
    const data = JSON.parse(fs.readFileSync(file, "utf8"));
    if (data && typeof data.workspaces === "object" && data.workspaces) return { file, data };
  } catch (_) {
    /* missing or torn registry is rebuilt below */
  }
  return { file, data: { version: 1, workspaces: {} } };
}

function writeRegistry(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = file + ".tmp-" + process.pid + "-" + Date.now();
  fs.writeFileSync(tmp, JSON.stringify(data, null, 2) + "\n", "utf8");
  fs.renameSync(tmp, file);
}

/** Remember id -> path so an id-only header can resolve later. */
function registerWorkspace(root, opts) {
  const dir = path.resolve(root || process.cwd());
  const id = workspaceId(dir);
  const { file, data } = readRegistry(opts);
  data.version = 1;
  data.workspaces = data.workspaces || {};
  data.workspaces[id] = { path: dir, last_seen: new Date().toISOString() };
  const entries = Object.entries(data.workspaces)
    .sort((a, b) => String(b[1].last_seen || "").localeCompare(String(a[1].last_seen || "")))
    .slice(0, MAX_REGISTRY_ENTRIES);
  data.workspaces = Object.fromEntries(entries);
  try {
    writeRegistry(file, data);
  } catch (_) {
    /* registry failure must not block a request */
  }
  return id;
}

/** Resolve a compact id to an existing directory, or "" when unknown. */
function lookupWorkspace(id, opts) {
  const key = String(id || "").trim();
  if (!/^[0-9a-f]{12}$/.test(key)) return "";
  const { data } = readRegistry(opts);
  const entry = data.workspaces && data.workspaces[key];
  if (!entry || !entry.path) return "";
  try {
    if (fs.statSync(entry.path).isDirectory()) return path.resolve(entry.path);
  } catch (_) {
    return "";
  }
  return "";
}

module.exports = {
  ROOT,
  PLUGIN_DIR,
  SERVER_DIR,
  serverPaths,
  pluginPaths,
  ensureServerWorkspace,
  readMergedSyllabus,
  splitEntries,
  entryIdentity,
  clearMergeCache,
  workspaceId,
  registerWorkspace,
  lookupWorkspace,
  registryPath,
};
